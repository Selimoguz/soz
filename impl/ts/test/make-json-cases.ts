// make-json-cases.ts — Writes conformance/cases/13-json-equivalents.json: every checker case of files
// 01 to 08 whose plan the JSON syntax can write, written in JSON, expecting what the s-expression gives
// (validity, error codes, effects, approval, call bound, stop). Error positions differ between the two
// syntaxes and are left out. Run it again when cases are added:
//
//   node --experimental-strip-types --disable-warning=ExperimentalWarning test/make-json-cases.ts

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { checkPlan, readPlan, operationsFromJson, policyFromJson, actorFromJson, parseJson, canonicalJson, type Json } from "../src/index.ts";
import { isObject } from "../src/exact.ts";
import { planToJson } from "../src/json-plan.ts";

const folder = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..", "conformance");
const ops = operationsFromJson(parseJson(readFileSync(join(folder, "operations.json"), "utf8")));
const out: Json[] = [];
let skipped = 0;

for (const f of readdirSync(join(folder, "cases")).filter(f => /^0[1-8]-/.test(f)).sort()) {
  const file = parseJson(readFileSync(join(folder, "cases", f), "utf8"));
  if (!isObject(file) || !Array.isArray(file.cases)) continue;
  for (const c of file.cases) {
    if (!isObject(c) || c.tools !== undefined) continue;
    const plan = Array.isArray(c.plan) ? c.plan.join("\n") : String(c.plan);
    let json: string | null = null;
    try { json = planToJson(readPlan(plan)); } catch { /* a syntax case: nothing to write */ }
    if (json === null) { skipped++; continue; }
    const message = c.message !== undefined ? c.message : file.message ?? null;
    const policy = c.policy !== undefined ? c.policy : file.policy;
    const actor = c.actor !== undefined ? c.actor : file.actor;
    const r = checkPlan(plan, { message: typeof message === "string" ? message : null, operations: ops,
                                policy: policy ? policyFromJson(policy) : [], actor: actorFromJson(actor ?? undefined) });
    const kase: { [k: string]: Json } = { name: `${f.replace(/\.json$/, "")}: ${c.name}`, message, plan: json };
    if (policy !== undefined) kase.policy = policy;
    if (actor !== undefined) kase.actor = actor;
    kase.expect = parseJson(canonicalJson({
      valid: r.valid, errors: r.errors.map(e => ({ code: e.code })), only: true, effects: r.effects,
      requires_approval: r.requiresApproval, max_calls: r.maxCalls, may_stop: r.mayStop,
    }));
    out.push(kase);
  }
}

const text = JSON.stringify({
  description: "The checker cases of files 01 to 08 in the JSON syntax (SPEC 2.1), generated by impl/ts/test/make-json-cases.ts: each must give what its s-expression gives. Positions are not compared.",
  message: null,
  cases: JSON.parse(canonicalJson(out)),
}, null, 2) + "\n";
writeFileSync(join(folder, "cases", "13-json-equivalents.json"), text);
console.log(`${out.length} cases written, ${skipped} skipped (the JSON syntax cannot write their plans)`);
